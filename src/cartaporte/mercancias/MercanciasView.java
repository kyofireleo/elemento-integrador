    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAceptarActionPerformed
        CartaPorte.Mercancias.Autotransporte auto = this.mercancias.new Autotransporte();
        auto.setPermSCT(txtTipoPermiso.getText().trim());
        auto.setNumPermisoSCT(txtPermisoSCT.getText().trim());
        
        CartaPorte.Mercancias.Autotransporte.IdentificacionVehicular id = auto.new IdentificacionVehicular();
        id.setPlacaVM(txtIdPlaca.getText().trim());
        id.setConfigVehicular(txtIdConfigVehicular.getText().trim());
        id.setAnioModeloVM(new Integer(txtIdAnioModelo.getText().trim()));
        id.setPesoBrutoVehicular(new BigDecimal(txtIdPesoBrutoV.getText().trim()));
        auto.setIdentificacionVehicular(id);
        
        CartaPorte.Mercancias.Autotransporte.Seguros seg = auto.new Seguros();
        seg.setAseguraCarga(txtSegAseguraCarga.getText().trim());
        seg.setAseguraRespCivil(txtSegAseguraRC.getText().trim());
        seg.setPolizaCarga(txtSegPolizaCarga.getText());
        seg.setPolizaRespCivil(txtSegPolizaRC.getText().trim());
        seg.setPrimaSeguro(new BigDecimal(txtSegPrima.getText().trim()));
        auto.setSeguros(seg);
        
        this.mercancias.setAutotransporte(auto);
        
        this.setVisible(false);
        this.cartaPorteView.returnFromMercancias(mercancias);
    }//GEN-LAST:event_btnAceptarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int row = this.tableMercancias.getSelectedRow();
        CartaPorte.Mercancias.Mercancia merca = this.mercancias.getMercancias().get(row);
        
        this.claveProdSat.setText(merca.getClaveSTCC());
        this.claveUnidad.setText(merca.getClaveUnidad());
        this.unidad.setText(merca.getUnidad());
        this.cantidad.setText(merca.getCantidad().toString());
        this.descripcion.setText(merca.getDescripcion());
        if(merca.getValorMercancia() != null && merca.getValorMercancia().compareTo(BigDecimal.ZERO) == 1){
            this.precio.setText(merca.getValorMercancia() != null ? merca.getValorMercancia().toString() : "");
            this.comboMoneda.setSelectedItem(merca.getMoneda());
        }
        this.pesoKg.setText(merca.getPesoEnKg().toString());
        
        eliminarMercanciaSeleccionada(row);
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int row = this.tableMercancias.getSelectedRow();
        
        eliminarMercanciaSeleccionada(row);
    }//GEN-LAST:event_btnEliminarActionPerformed
    
    private void eliminarMercanciaSeleccionada(int row){
        DefaultTableModel model = (DefaultTableModel)this.tableMercancias.getModel();
        model.removeRow(row);
        
        this.mercancias.getMercancias().remove(row);
        calcularTotalesTabla();
    }
    
