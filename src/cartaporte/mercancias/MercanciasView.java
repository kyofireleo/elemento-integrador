    private void agregarConceptoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_agregarConceptoActionPerformed
        CartaPorte.Mercancias.Mercancia merca = this.mercancias.new Mercancia();
        
        merca.setCantidad(new BigDecimal(cantidad.getText().trim()));
        merca.setClaveSTCC(claveProdSat.getText().trim());
        merca.setClaveUnidad(claveUnidad.getText().trim());
        merca.setUnidad(unidad.getText());
        merca.setDescripcion(descripcion.getText().trim());
        merca.setPesoEnKg(new BigDecimal(pesoKg.getText().trim()));
        
        if(!precio.getText().trim().isEmpty()){
            merca.setValorMercancia(new BigDecimal(precio.getText().trim()));
            merca.setMoneda(comboMoneda.getSelectedItem().toString());
        }
        
        this.mercancias.getMercancias().add(merca);
        
        NumberFormat usFormatter = NumberFormat.getCurrencyInstance(Locale.US);
        DefaultTableModel model = (DefaultTableModel)tableMercancias.getModel();
        Object[] row = new Object[4];
        
        row[0] = merca.getCantidad();
        row[1] = merca.getUnidad();
        row[2] = merca.getDescripcion();
        row[3] = (merca.getValorMercancia() == null ? "" : usFormatter.format(merca.getValorMercancia()));
        
        model.addRow(row);
        
        calcularTotalesTabla();
    }//GEN-LAST:event_agregarConceptoActionPerformed

    private void calcularTotalesTabla(){
        lblNumTotalMercas.setText("" + this.mercancias.getMercancias().size());
        BigDecimal pesoBruto = BigDecimal.ZERO;
        
        for(CartaPorte.Mercancias.Mercancia merca : this.mercancias.getMercancias()){
            pesoBruto = pesoBruto.add(merca.getPesoEnKg());
        }
        
        NumberFormat numFormatter = NumberFormat.getNumberInstance();
        lblPesoBrutoTotal.setText(numFormatter.format(pesoBruto));
    }
    
